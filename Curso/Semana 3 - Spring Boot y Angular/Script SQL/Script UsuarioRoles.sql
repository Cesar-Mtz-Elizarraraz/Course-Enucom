-- TABLA ROLES
CREATE TABLE CURSO_ROLES (
    ID_ROL NUMBER,
    PRIVILEGIO NVARCHAR2(50),
    CONSTRAINT PK_ROLES PRIMARY KEY(ID_ROL)
);

-- TABLA USUARIOS
CREATE TABLE CURSO_USUARIOS (
    ID_USUARIO NUMBER,
    NOMBRE NVARCHAR2(100),
    APP NVARCHAR2(50),
    APM NVARCHAR2(50),
    SEXO NVARCHAR2(25),
    CORREO NVARCHAR2(100) NOT NULL,
    FECHA_NACIMIENTO DATE,
    FECHA_CREACION DATE,
    ROL_ID NUMBER,
    CONSTRAINT PK_USUARIOS PRIMARY KEY(ID_USUARIO),
    CONSTRAINT FK_ROL_ID FOREIGN KEY (ROL_ID) REFERENCES CURSO_ROLES(ID_ROL)
);

-- TRIGGER PARA FECHA DE CREACION
CREATE OR REPLACE TRIGGER TR_C_US_FECHAS
BEFORE INSERT ON CURSO_USUARIOS
FOR EACH ROW
BEGIN
    IF :NEW.FECHA_CREACION IS NULL THEN
        :NEW.FECHA_CREACION := SYSDATE;
    END IF;
END;
