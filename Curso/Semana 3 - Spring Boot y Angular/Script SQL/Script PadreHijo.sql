INCREMENT BY 1
NOCYCLE
NOCACHE;

-- TRIGGER PARA EL ID
CREATE OR REPLACE TRIGGER TR_HIJO_ID
BEFORE INSERT ON HIJO
FOR EACH ROW
BEGIN
    IF :NEW.ID_HIJO IS NULL THEN
        :NEW.ID_HIJO := SEQ_HIJO.NEXTVAL;
    END IF;
END;
