-- SECUENCIA PADRE
-- DROP SEQUENCE SEQ_PADRE;
CREATE SEQUENCE SEQ_PADRE
START WITH 7
INCREMENT BY 1
NOCYCLE
NOCACHE;

-- TRIGGER PARA EL ID
CREATE OR REPLACE TRIGGER TR_PADRE_ID
BEFORE INSERT ON PADRE
FOR EACH ROW
BEGIN
    IF :NEW.ID_PADRE IS NULL THEN
        :NEW.ID_PADRE := SEQ_PADRE.NEXTVAL;
    END IF;
END;
/ -- INDICADOR

-- SECUENCIA HIJO
-- DROP SEQUENCE SEQ_HIJO;
CREATE SEQUENCE SEQ_HIJO
