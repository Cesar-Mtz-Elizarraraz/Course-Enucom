CREATE TABLE VIDEOJUEGO(
    ID_VIDEOJUEGO NUMBER,
    NOMBRE NVARCHAR2(100),
    GENERO NVARCHAR2(50),
    DESARROLLADOR NVARCHAR2(100),
    PLATAFORMA NVARCHAR2(50),
    PRECIO NUMBER,
    CLASIFICACION NVARCHAR2(10),
    COPIAS_VENDIDAS NUMBER,
    CONSTRAINT VIDEOJUEGO_PK PRIMARY KEY(ID_VIDEOJUEGO)
);

-- SECUENCIA
-- DROP SEQUENCE SEQ_VJUEGO;
CREATE SEQUENCE SEQ_VJUEGO
START WITH 1
INCREMENT BY 1
NOCYCLE
NOCACHE;

-- TRIGGER PARA EL ID
CREATE OR REPLACE TRIGGER TR_VJUEGO_ID
BEFORE INSERT ON VIDEOJUEGO
FOR EACH ROW
BEGIN
    IF :NEW.ID_VIDEOJUEGO IS NULL THEN
        :NEW.ID_VIDEOJUEGO := SEQ_VJUEGO.NEXTVAL;
    END IF;
END;
