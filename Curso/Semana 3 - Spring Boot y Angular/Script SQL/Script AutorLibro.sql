-- TABLA AUTOR
CREATE TABLE AUTOR (
    ID_AUTOR NUMBER,
    NOMBRE NVARCHAR2(100),
    NACIONALIDAD NVARCHAR2(50),
    FECHA_NACIMIENTO DATE,
    CONSTRAINT AUTOR_NOMBRE CHECK (NOMBRE IS NOT NULL AND TRIM(NOMBRE) <> ''),
    CONSTRAINT AUTOR_PK PRIMARY KEY(ID_AUTOR)
);

-- TABLA LIBRO
CREATE TABLE LIBRO (
    ID_LIBRO NUMBER,
    TITULO NVARCHAR2(150) NOT NULL,
    GENERO NVARCHAR2(50),
    ANIO_PUBLICACION NUMBER(4),
    PRECIO NUMBER(10,2),
    AUTOR_ID NUMBER,
    CONSTRAINT LIBRO_PK PRIMARY KEY(ID_LIBRO),
    CONSTRAINT LIBRO_AUTOR_FK FOREIGN KEY (AUTOR_ID) REFERENCES AUTOR(ID_AUTOR)
);

DROP TABLE LIBRO;

-- SECUENCIAS PARA LAS TABLAS
CREATE SEQUENCE SEQ_AUTOR_ID START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_LIBRO_ID START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;


-- TRIGGER PARA EL ID AUTOR
CREATE OR REPLACE TRIGGER TR_AUTOR_ID
BEFORE INSERT ON AUTOR
FOR EACH ROW
BEGIN
    IF :NEW.ID_AUTOR IS NULL THEN
        :NEW.ID_AUTOR := SEQ_AUTOR_ID.NEXTVAL;
    END IF;
END;
/ -- INDICADOR

-- TRIGGER PARA EL ID LIBRO
CREATE OR REPLACE TRIGGER TR_LIBRO_ID
BEFORE INSERT ON LIBRO
FOR EACH ROW
BEGIN
    IF :NEW.ID_LIBRO IS NULL THEN
        :NEW.ID_LIBRO := SEQ_LIBRO_ID.NEXTVAL;
    END IF;
END;
/ -- INDICADOR

