CREATE TABLE DINERO(
    ID_DINERO NUMBER GENERATED ALWAYS AS IDENTITY,
    TIPO NVARCHAR2(50),
    CANTIDAD NUMBER(10,0),
    DENOMINACION NUMBER(10,2),
    CONSTRAINT DINERO_PK PRIMARY KEY(ID_DINERO),
    CONSTRAINT DINERO_CANTIDAD CHECK(CANTIDAD >= 0),
    CONSTRAINT DINERO_DENOMINACION CHECK(DENOMINACION >= 0)
);

