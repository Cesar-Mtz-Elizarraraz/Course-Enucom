CREATE TABLE VETERINARIAS (
    ID_VETERINARIA NUMBER GENERATED ALWAYS AS IDENTITY,
    NOMBRE NVARCHAR2(50),
    DIRECCION NVARCHAR2(100),
    TELEFONO NUMBER,
    CONSTRAINT PK_VETERINARIAS PRIMARY KEY(ID_VETERINARIA)
);


CREATE TABLE RESPONSABLES (
    ID_RESPONSABLE NUMBER GENERATED ALWAYS AS IDENTITY,
    NOMBRE NVARCHAR2(50),
    CONTACTO NUMBER,
    VETERINARIA_ID NUMBER,
    CONSTRAINT PK_RESPONSABLES PRIMARY KEY(ID_RESPONSABLE)
    -- CONSTRAINT FK_RESPONSABLE_VETERINARIA FOREIGN KEY (VETERINARIA_ID) REFERENCES VETERINARIAS(ID_VETERINARIA)
);


CREATE TABLE CLIENTES (
    ID_CLIENTE NUMBER GENERATED ALWAYS AS IDENTITY,
    NOMBRE NVARCHAR2(50),
    DIRECCION NVARCHAR2(100),
    CONTACTO NUMBER(10),
    CONSTRAINT PK_CLIENTES PRIMARY KEY(ID_CLIENTE)
);



CREATE TABLE MASCOTAS (
    ID_MASCOTA NUMBER GENERATED ALWAYS AS IDENTITY,
    NOMBRE NVARCHAR2(15),
    RAZA NVARCHAR2(15),
    EDAD NUMBER,
    RAZON_CITA NVARCHAR2(100),
    CLIENTE_ID NUMBER,
    RESPONSABLE_ID NUMBER,
    VETERINARIA_ID NUMBER,
    CONSTRAINT PK_MASCOTAS PRIMARY KEY(ID_MASCOTA)
    -- CONSTRAINT FK_CLIENTE_ID FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTES(ID_CLIENTE),
    -- CONSTRAINT FK_RESPONSABLE_ID FOREIGN KEY (RESPONSABLE_ID) REFERENCES RESPONSABLES(ID_RESPONSABLE)
);

-- TRIGGER PARA ACTUALIZAR EL ID DE LA VETERINARIA EN LA TABLA 'MASCOTAS'
CREATE OR REPLACE TRIGGER TR_UPDATE_VETERINARIA_RESPONSABLE
AFTER UPDATE ON RESPONSABLES
FOR EACH ROW
BEGIN
    -- VERIFICAR SI CAMBIO EL ID DE LA VETERINARIA
    IF :OLD.VETERINARIA_ID != :NEW.VETERINARIA_ID THEN
        -- ACTUALIZAR EL ID DE LA VETERINARIA A LA NUEVA ASIGNACIÓN DEL RESPONSABLE
        UPDATE MASCOTAS 
        SET VETERINARIA_ID = :NEW.VETERINARIA_ID
        WHERE RESPONSABLE_ID = :NEW.ID_RESPONSABLE;
    END IF;
END;
